"""Validate the generated research data contract (no third-party dependencies).

Run after build_data.py, before astro build. Validates actual artifact joins,
schema field types, portable resource URLs and hashes, not fixed dataset sizes.
"""
import argparse
import hashlib
import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "public" / "data"


def read(name):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def check_type(value, expected):
    if expected == "null":
        return value is None
    if expected == "integer":
        return type(value) is int
    if expected == "number":
        return type(value) in (int, float)
    return isinstance(value, {"string": str, "boolean": bool, "array": list, "object": dict}[expected])


def validate_schema(value, rules, path="workspace"):
    if "const" in rules:
        assert value == rules["const"] and type(value) is type(rules["const"]), f"Invalid constant: {path}"
    if "enum" in rules:
        assert value in rules["enum"], f"Invalid enum: {path}"
    if "type" in rules:
        allowed = rules["type"] if isinstance(rules["type"], list) else [rules["type"]]
        assert any(check_type(value, kind) for kind in allowed), f"Invalid type: {path}"
    if value is None:
        return
    if "minimum" in rules:
        assert value >= rules["minimum"], f"Below minimum: {path}"
    if "maximum" in rules:
        assert value <= rules["maximum"], f"Above maximum: {path}"
    if "minLength" in rules:
        assert len(value) >= rules["minLength"], f"Empty value: {path}"
    if isinstance(value, dict):
        properties = rules.get("properties", {})
        assert set(rules.get("required", [])).issubset(value), f"Missing field: {path}"
        for key, entry in value.items():
            additional = rules.get("additionalProperties", True)
            assert key in properties or additional is not False, f"Unexpected field: {path}.{key}"
            child = properties.get(key, additional if isinstance(additional, dict) else {})
            validate_schema(entry, child, f"{path}.{key}")
    elif isinstance(value, list) and "items" in rules:
        for index, entry in enumerate(value):
            validate_schema(entry, rules["items"], f"{path}[{index}]")


def validate_workspace(workspace, corpus, generated):
    from workspace_store import validate_venues
    validate_schema(workspace, read("workspace.schema.json"))
    assert workspace["generated"] == generated, "Mixed workspace snapshot"
    validate_venues(workspace["venues"])
    ids = {paper["id"] for paper in corpus}
    dois = {paper["doi"] for paper in corpus if paper.get("doi")}
    seen = set()
    for paper in workspace["papers"]:
        assert paper["id"] == "discovery:" + paper["doi"] and paper["doi"] not in dois, "Discovery must be independent from the main corpus"
        assert paper["id"] not in ids | seen, "Duplicate workspace record"
        seen.add(paper["id"])
    known = ids | seen
    assert set(workspace["articles"]) <= known, "Orphan Wiki article"
    assert set(workspace["analyses"]) <= known, "Orphan AI draft"
    for article in workspace["articles"].values():
        revisions = [entry["revision"] for entry in article["history"]]
        assert revisions == sorted(set(revisions)) and all(version <= article["revision"] for version in revisions), "Invalid Wiki history"
        if revisions and revisions[-1] == article["revision"]:
            assert article["history"][-1]["content"] == {key: article[key] for key in ("title", "zh", "category", "tags", "body")}, "Current Wiki differs from its revision"
    for old, target in workspace["id_redirects"].items():
        assert old != target and target in known, "Unresolved workspace ID redirect"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site-dir", type=Path, help="Also validate the curated guides generated by Astro in this output directory")
    args = parser.parse_args()
    manifest = read("manifest.json")
    assert manifest["schema_version"].split(".")[0] == "1", "Unexpected contract major version"
    resource_ids = [r["id"] for r in manifest["resources"]]
    assert len(resource_ids) == len(set(resource_ids)), "Duplicate resource IDs"
    for resource in manifest["resources"]:
        url = urlparse(resource["url"])
        assert not url.scheme and not url.netloc and not url.path.startswith("/"), "Resources must be relative"
        target = (DATA / url.path).resolve()
        assert target.parent == DATA.resolve(), "Unexpected resource path outside data directory"
        payload = target.read_bytes()
        assert len(payload) == resource["bytes"], f"Size mismatch: {target.name}"
        assert hashlib.sha256(payload).hexdigest() == resource["sha256"], f"Hash mismatch: {target.name}"
    combined, qce, tqe = (read(name) for name in ("papers.json", "qce.json", "tqe.json"))
    rows = combined["papers"]
    assert rows == qce["papers"] + tqe["papers"], "Combined corpus differs from browser data"
    for dataset in (combined, qce, tqe):
        assert dataset["count"] == len(dataset["papers"]), "Envelope count mismatch"
        assert dataset["generated"] == manifest["generated"], "Mixed generation snapshots"
    ids = {r["id"] for r in rows}
    assert len(ids) == len(rows), "Duplicate Paper IDs"
    schema = read("paper.schema.json")
    for row in rows:
        assert set(schema["required"]).issubset(row), f"Missing field: {row['id']}"
        for key, rules in schema["properties"].items():
            if key not in row:
                continue
            value = row[key]
            if "enum" in rules:
                assert value in rules["enum"], f"Unknown {key}: {row['id']}"
            if "type" in rules:
                allowed = rules["type"] if isinstance(rules["type"], list) else [rules["type"]]
                assert any(check_type(value, t) for t in allowed), f"Invalid {key} type: {row['id']}"
            if value is not None and "minimum" in rules:
                assert value >= rules["minimum"], f"Invalid {key} range: {row['id']}"
            if isinstance(value, list) and "items" in rules:
                assert all(check_type(item, rules["items"]["type"]) for item in value), f"Invalid {key} item: {row['id']}"
        assert row["id"] == f"{row['source']}:{row['source_id']}", f"ID/source mismatch: {row['id']}"
    quality = read("quality.json")
    assert quality["generated"] == manifest["generated"]
    assert quality["overall"] == manifest["counts"]
    assert quality["overall"]["records"] == len(rows)
    assert quality["overall"]["research_records"] == sum(not p["front_matter"] for p in rows)
    assert quality["overall"]["front_matter"] == sum(p["front_matter"] for p in rows)
    for source, counts in quality["by_source"].items():
        subset = [p for p in rows if p["source"] == source]
        research = [p for p in subset if not p["front_matter"]]
        assert counts["records"] == len(subset)
        assert counts["research_records"] == len(research)
        assert counts["research_with_abstract"] == sum(bool(p["abstract"]) for p in research)
        assert counts["research_with_doi"] == sum(bool(p["doi"]) for p in research)
        assert counts["research_with_arxiv"] == sum(bool(p["arxiv"]) for p in research)
    assert sum(quality["research_by_category"].values()) == quality["overall"]["research_records"]
    assert sum(quality["research_by_year"].values()) == quality["overall"]["research_records"]
    assert read("stats.json")["totals"]["all"] == quality["overall"]["research_records"]
    topic_map = read('research-map.json')
    assert topic_map['generated'] == manifest['generated'], 'Mixed research map snapshot'
    topic_keys = {topic['key'] for topic in topic_map['topics']}
    assert len(topic_keys) == len(topic_map['topics']) and topic_keys, 'Empty or duplicate subtopics'
    associated = set()
    row_index = {row['id']: row for row in rows}
    for topic in topic_map['topics']:
        matches = topic['matched_papers']
        assert topic['matched_count'] == len(matches)
        assert len({m['id'] for m in matches}) == len(matches)
        for match in matches:
            assert match['id'] in ids and not row_index[match['id']]['front_matter']
            assert match['score'] > 0 and match['matched_terms']
            associated.add(match['id'])
        assert all(urlparse(source['url']).scheme == 'https' for source in topic['sources'])
    assert topic_map['counts']['associated_records'] == len(associated)
    assert topic_map['counts']['topics'] == len(topic_map['topics'])
    assert set(key for domain in topic_map['domains'] for key in domain['topics']) == topic_keys
    for redirect in read("id-redirects.json")["redirects"]:
        assert redirect["old_id"] not in ids and redirect["new_id"] in ids, "Unresolved ID replacement"
    validate_workspace(read("workspace.json"), rows, manifest["generated"])
    print(f"Agent data validated: {len(rows)} records, {len(manifest['resources'])} resources, schema {manifest['schema_version']}")
    if args.site_dir:
        published_workspace = json.loads((args.site_dir / "data/workspace.json").read_text(encoding="utf-8"))
        assert published_workspace == read("workspace.json"), "Published workspace differs from the reviewed snapshot"
        exported = json.loads((args.site_dir / "data" / "guides.json").read_text(encoding="utf-8"))
        assert exported["schema_version"] == manifest["schema_version"], "Guide export version mismatch"
        assert exported["generated"] == manifest["generated"], "Curated export built against a different data snapshot"
        guides = exported["guides"]
        cs4q, venues = guides["cs4q"], guides["venues"]
        assert len(cs4q["entries"]) == cs4q["counts"]["total"]
        assert len({p["id"] for p in cs4q["entries"]}) == len(cs4q["entries"])
        for kind, label in (("journals", "journals"), ("conferences", "confs")):
            assert len(venues[kind]) == venues["counts"][label]
            assert len({v["id"] for v in venues[kind]}) == len(venues[kind])
        for guide in guides.values():
            assert guide["page_url"].endswith("/") and not urlparse(guide["page_url"]).netloc
            assert guide["declared_source_review_date"] and guide["source_file"]
        assert guides["openqasm"]["content_markdown"].strip()
        print(f"Curated data validated: {len(cs4q['entries'])} CS4Q entries, {len(venues['journals'])} journals, {len(venues['conferences'])} conferences")


if __name__ == "__main__":
    main()
